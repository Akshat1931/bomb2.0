  function imageToData(img, maxDim = 2400) {
    const sc = Math.min(1, maxDim / Math.max(img.naturalWidth, img.naturalHeight));
    const W = Math.round(img.naturalWidth * sc), H = Math.round(img.naturalHeight * sc);
    const cv = document.createElement('canvas');
    cv.width = W; cv.height = H;
    const g = cv.getContext('2d', { willReadFrequently: true });
    g.drawImage(img, 0, 0, W, H);
    return g.getImageData(0, 0, W, H);
  }

  function cropUri(img, b, pad = 4) {
    const c = document.createElement('canvas');
    const w = b.x1 - b.x0 + pad * 2, h = b.y1 - b.y0 + pad * 2;
    c.width = w; c.height = h;
    c.getContext('2d').drawImage(img, b.x0 - pad, b.y0 - pad, w, h, 0, 0, w, h);
    return c.toDataURL();
  }

  const glyphUriCache = new Map();

  function setupInputs() {
    const dz = $('astrologyDropzone');
    if (dz) {
      dz.addEventListener('dragover', (e) => { e.preventDefault(); dz.classList.add('dragover'); });
      dz.addEventListener('dragleave', () => dz.classList.remove('dragover'));
      dz.addEventListener('drop', (e) => {
        e.preventDefault();
        e.stopPropagation();
        dz.classList.remove('dragover');
        if (window.BombDragDrop) {
          window.BombDragDrop.handleDataTransfer(e.dataTransfer, (file) => { if (file) loadFile(file); });
        } else {
          const f = [...(e.dataTransfer?.files || [])].find(x => x.type.startsWith('image/'));
          if (f) loadFile(f);
        }
      });
    }
    // Ctrl+V on this tab: the star list as text, or a screenshot (Discord links go via dragdrop-helper.js)
    // document + bubble phase, like the other modules: the build's access gate (window, capture) runs first
    document.addEventListener('paste', (e) => {
      if (!$('astrologySection')?.classList.contains('active')) return;
      const el = document.activeElement;
      if (el && (el.tagName === 'TEXTAREA' || (el.tagName === 'INPUT' && el.type !== 'file'))) return;
      const t = e.clipboardData && e.clipboardData.getData('text');
      if (t && looksLikeStarList(t)) {
        e.preventDefault();
        e.stopImmediatePropagation();
        setStarText(t.trim());
        $('astroStarText').value = state.starText;
        state.status = { text: `Star list loaded: ${parseStarList(t).count} names ✓`, ok: true };
        update();
        return;
      }
      for (const item of (e.clipboardData?.items || [])) {
        if (item.type.startsWith('image/')) {
          e.preventDefault();
          const f = item.getAsFile();
          if (f) loadFile(f);
          return;
        }
      }
    });
  }

  function loadFile(file) {
    const img = new Image();
    img.onload = () => handleImage(img);
    img.onerror = () => { state.status = { text: 'Could not open that file as an image.', ok: false }; update(); };
    img.src = URL.createObjectURL(file);
  }

  function readMap(img) {
    const d = imageToData(img);
    const sky = readSkyMap(d.data, d.width, d.height, astroRefs());
    const found = Object.keys(sky.byName).length;
    if (found < 60) {
      state.status = { text: `Only ${found} symbols recognised on that map — kept the previous map.`, ok: false };
      return;
    }
    const missing = CONSTELLATIONS.filter(n => !sky.byName[n]);
    setMap({ ...sky.byName, _missing: missing, _at: Date.now() });
    state.status = {
      text: `Sky map read: ${found}/88 symbols${missing.length ? ` — not found: ${missing.join(', ')}` : ''}.`,
      ok: !missing.length
    };
  }

  function readScreen(img) {
    const d = imageToData(img);
    const r = readDefuser(d.data, d.width, d.height, astroRefs());
    const thumbs = r.buttons.map(b => (b ? cropUri(img, b.box) : ''));
    state.read = { ...r, uri: img.src, w: d.width, h: d.height, thumbs };
    state.stars = r.stars;
    state.names = r.buttons.map(b => (b ? b.name : null));
    const weak = r.buttons.filter(b => !b || b.margin < 0.5).length;
    state.status = {
      text: `${r.stars} stars · buttons: ${r.buttons.map((b, i) => `${i + 1} ${b ? b.name : '?'}`).join(', ')}${weak ? ` · ${weak} unsure` : ''}${r.bigBlobs ? ' · a star may hide another — check the count' : ''}`,
      ok: !weak && !r.bigBlobs
    };
  }

  function handleImage(img) {
    try {
      // the helper's sky map is wide; the defuser's module screenshot is square
      if (img.naturalWidth / img.naturalHeight > 1.3) readMap(img);
      else readScreen(img);
    } catch (e) {
      state.status = { text: `Could not read that image (${e.message || e}).`, ok: false };
    }
    update();
  }

  function solve() {
    const list = parseStarList(state.starText);
    const listOk = list.count >= 40;
    const mapOk = Boolean(state.map);
    const haveInput = state.read !== null || state.names.some(Boolean) || state.stars !== null;
    let solved = haveInput && state.stars !== null ? solveAstrology(state.stars, state.names, state.map || {}, list) : null;
    if (solved && (!mapOk || !listOk)) {
      solved = { ...solved, answer: null, problem: `Paste this game's ${[!mapOk && 'sky map', !listOk && 'star list'].filter(Boolean).join(' and ')} first.` };
    }
    return { list, listOk, mapOk, haveInput, solved };
  }


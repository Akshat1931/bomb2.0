  function chipThumb(img, b) {
    const c = document.createElement('canvas');
    const w = b.x1 - b.x0 + 1, h = b.y1 - b.y0 + 1;
    c.width = w; c.height = h;
    c.getContext('2d').drawImage(img, b.x0, b.y0, w, h, 0, 0, w, h);
    return c.toDataURL();
  }

  function handleImage(img, dataUri) {
    const W = img.naturalWidth || img.width, H = img.naturalHeight || img.height;
    const cv = document.createElement('canvas');
    cv.width = W; cv.height = H;
    const ctx = cv.getContext('2d', { willReadFrequently: true });
    ctx.drawImage(img, 0, 0);
    const data = ctx.getImageData(0, 0, W, H).data;
    const c = readCircuit(data, W, H);

    // no orange terminals: maybe it's the colour legend
    if (!(c.terminals && c.terminals.length === 2)) {
      const lg = readLegend(data, W, H, learned());
      const valued = lg.ok ? lg.chips.filter((ch) => ch.value !== null).length : 0;
      if (valued >= 3) {
        const chips = lg.chips.map((ch) => ({ ...ch, thumb: chipThumb(img, ch.box), read: ch.value }));
        applyLegend(chips);
        const check = chips.filter((ch) => !ch.sure).length;
        S.note = { text: check ? `Legend read — check ${check} value${check > 1 ? 's' : ''} (marked)` : `Legend read ✓ ${chips.length} colours`, ok: !check };
        render();
        return;
      }
    }
    S.shot = { uri: dataUri, W, H };
    S.circuit = c;
    S.colors = c.resistors ? c.resistors.map((r) => r.color) : [];
    S.note = c.ok ? { text: `Circuit read ✓ ${c.resistors.length} resistors`, ok: true } : null;
    render();
  }

  function loadFile(file) {
    const reader = new FileReader();
    reader.onload = () => {
      const img = new Image();
      img.onload = () => handleImage(img, reader.result);
      img.onerror = () => { S.note = { text: '⚠ Could not open that file as an image.', ok: false }; render(); };
      img.src = reader.result;
    };
    reader.readAsDataURL(file);
  }

  function solve() {
    const manual = parseCircuitManual(S.manualText);
    const count = Object.keys(manual).length;
    if (!S.circuit || !S.circuit.ok || !count) return { manual, count, solved: null };
    const rs = S.circuit.resistors.map((r, i) => ({ ...r, color: S.colors[i] || r.color }));
    return { manual, count, solved: solveCircuit(rs, S.circuit.A, S.circuit.B, manual) };
  }


  const { classifyColor, components, readCircuit } = (function () {
    // Circuit screenshot reader (pure pixel maths on RGBA data, so it also runs in tests).
    // - resistors: the thick blobs (wires are ~3 px lines, terminal dots are small circles)
    // - terminals: the orange (amber) dots
    // - nodes: each connected piece of wire outside the resistors is one electrical node

    const PANEL = [31, 34, 40]; // inner panel fill
    const WIRE = [203, 213, 225];

    /** Resistor body colour → name (the game uses Tailwind colours: violet-600, blue-600 …). */
    function classifyColor(r, g, b) {
      const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2, s = mx - mn;
      if (s < 30) return l > 200 ? 'white' : 'gray';
      let h;
      if (mx === r) h = ((g - b) / s) * 60;
      else if (mx === g) h = (2 + (b - r) / s) * 60;
      else h = (4 + (r - g) / s) * 60;
      if (h < 0) h += 360;
      if (h < 14 || h >= 330) return 'red';
      if (h < 36) return 'orange';
      if (h < 70) return 'yellow';
      if (h < 175) return 'green';
      if (h < 245) return 'blue';
      return 'violet';
    }

    const isAmber = (r, g, b) => r > 200 && g > 120 && g < 190 && b < 70;

    // The inner panel: the largest patch of pixels closest to the panel fill (not the page or the frame,
    // which are only a few shades away — JPEG / resizing blur them together otherwise).
    const PAGE = [22, 25, 29], FRAME = [44, 48, 54];
    function findPanel(data, W, H) {
      const d2 = (i, c) => (data[i] - c[0]) ** 2 + (data[i + 1] - c[1]) ** 2 + (data[i + 2] - c[2]) ** 2;
      const mask = new Uint8Array(W * H);
      for (let p = 0; p < W * H; p++) {
        const i = p * 4, dp = d2(i, PANEL);
        mask[p] = dp <= 300 && dp < d2(i, PAGE) && dp < d2(i, FRAME) ? 1 : 0;
      }
      const { comps } = components(mask, W, H, false);
      const big = comps.sort((a, b) => b.n - a.n)[0];
      if (!big || big.n < W * H * 0.15) return { x0: 0, y0: 0, x1: W - 1, y1: H - 1 };
      const pad = 3;
      return { x0: big.x0 + pad, y0: big.y0 + pad, x1: big.x1 - pad, y1: big.y1 - pad };
    }

    function components(mask, w, h, conn8 = true) {
      const lab = new Int32Array(w * h), comps = [];
      for (let s = 0; s < w * h; s++) {
        if (!mask[s] || lab[s]) continue;
        const id = comps.length + 1, st = [s];
        lab[s] = id;
        let x0 = w, y0 = h, x1 = -1, y1 = -1, n = 0, sx = 0, sy = 0;
        while (st.length) {
          const p = st.pop(), px = p % w, py = (p / w) | 0;
          n++; sx += px; sy += py;
          if (px < x0) x0 = px; if (px > x1) x1 = px; if (py < y0) y0 = py; if (py > y1) y1 = py;
          for (let dy = -1; dy <= 1; dy++) for (let dx = -1; dx <= 1; dx++) {
            if (!conn8 && dx && dy) continue;
            const nx = px + dx, ny = py + dy;
            if (nx < 0 || ny < 0 || nx >= w || ny >= h) continue;
            const q = ny * w + nx;
            if (mask[q] && !lab[q]) { lab[q] = id; st.push(q); }
          }
        }
        comps.push({ id, x0, y0, x1, y1, n, cx: sx / n, cy: sy / n });
      }
      return { lab, comps };
    }

    /**
     * @returns {{ ok, error?, panel, resistors:[{x,y,w,h,color,rgb,a,b,horizontal}], terminals:[{x,y,node}], A, B }}
     *   coordinates are in image pixels; a/b/A/B are node ids
     */
    function readCircuit(data, W, H) {
      const P = findPanel(data, W, H);
      const w = P.x1 - P.x0 + 1, h = P.y1 - P.y0 + 1;
      if (w < 40 || h < 40) return { ok: false, error: 'Circuit panel not found' };
      const px = (x, y) => ((P.y0 + y) * W + P.x0 + x) * 4;

      const ink = new Uint8Array(w * h);
      for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
        const i = px(x, y);
        const d = Math.max(Math.abs(data[i] - PANEL[0]), Math.abs(data[i + 1] - PANEL[1]), Math.abs(data[i + 2] - PANEL[2]));
        ink[y * w + x] = d > 22 ? 1 : 0;
      }
      // resistor bodies carry dark label text — fill it in so the body counts as solid
      // (summed-area table → "is every pixel in this square ink?")
      const r = Math.max(3, Math.round(Math.min(w, h) * 0.02));
      // dark label text (on white / yellow bodies) is almost the panel colour, so it reads as holes that
      // cut a narrow body into pieces — fill small holes enclosed by ink (the panel itself is huge)
      const solid = ink.slice();
      {
        const { lab: hl, comps: holes } = components(ink.map(v => 1 - v), w, h, false);
        const fill = new Uint8Array(holes.length + 1);
        for (const c of holes) {
          if (c.x0 > 0 && c.y0 > 0 && c.x1 < w - 1 && c.y1 < h - 1 && Math.max(c.x1 - c.x0, c.y1 - c.y0) < r * 5) fill[c.id] = 1;
        }
        for (let p = 0; p < w * h; p++) if (fill[hl[p]]) solid[p] = 1;
      }
      const sat = new Int32Array((w + 1) * (h + 1));
      for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
        sat[(y + 1) * (w + 1) + x + 1] = solid[y * w + x] + sat[y * (w + 1) + x + 1] + sat[(y + 1) * (w + 1) + x] - sat[y * (w + 1) + x];
      }
      const boxSum = (x0, y0, x1, y1) => sat[(y1 + 1) * (w + 1) + x1 + 1] - sat[y0 * (w + 1) + x1 + 1] - sat[(y1 + 1) * (w + 1) + x0] + sat[y0 * (w + 1) + x0];
      const core = new Uint8Array(w * h);
      const side = 2 * r + 1, need = side * side * 0.82; // label text leaves small dark holes
      for (let y = r; y < h - r; y++) for (let x = r; x < w - r; x++) {
        if (boxSum(x - r, y - r, x + r, y + r) >= need) core[y * w + x] = 1;
      }
      const { comps: cores } = components(core, w, h);

      const resistors = [];
      for (const c of cores) {
        const x0 = Math.max(0, c.x0 - r), y0 = Math.max(0, c.y0 - r), x1 = Math.min(w - 1, c.x1 + r), y1 = Math.min(h - 1, c.y1 + r);
        const bw = x1 - x0 + 1, bh = y1 - y0 + 1;
        const long = Math.max(bw, bh), short = Math.min(bw, bh);
        if (long / short < 1.3 || short < r * 2.5) continue; // terminal dots, junction blobs
        // body colour: the most common colour inside (ignores the label text)
        const hist = new Map();
        for (let y = y0 + 2; y <= y1 - 2; y++) for (let x = x0 + 2; x <= x1 - 2; x++) {
          const i = px(x, y);
          const k = (data[i] >> 3) << 10 | (data[i + 1] >> 3) << 5 | (data[i + 2] >> 3);
          hist.set(k, (hist.get(k) || 0) + 1);
        }
        let bestK = 0, bestN = -1;
        hist.forEach((n, k) => { if (n > bestN) { bestN = n; bestK = k; } });
        const rgb = [((bestK >> 10) & 31) * 8 + 4, ((bestK >> 5) & 31) * 8 + 4, (bestK & 31) * 8 + 4];
        // where a diagonal wire meets another, the wedge looks thick: it is wire-coloured (slate-300),
        // while white resistors are brighter (gray-100) — and a body is mostly one flat colour
        if ((rgb[0] - WIRE[0]) ** 2 + (rgb[1] - WIRE[1]) ** 2 + (rgb[2] - WIRE[2]) ** 2 < 22 ** 2) continue;
        // a small wire loop whose inside got filled as a "hole" is panel-coloured, not a body
        if ((rgb[0] - PANEL[0]) ** 2 + (rgb[1] - PANEL[1]) ** 2 + (rgb[2] - PANEL[2]) ** 2 < 40 ** 2) continue;
        let flat = 0, area = 0;
        for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) {
          const i = px(x, y); area++;
          if ((data[i] - rgb[0]) ** 2 + (data[i + 1] - rgb[1]) ** 2 + (data[i + 2] - rgb[2]) ** 2 <= 1600) flat++;
        }
        if (flat < area * 0.4) continue;
        // tighten the box to the body colour: the rough box is a few px too big, and a wire passing
        // close by (a diagonal skimming a corner) must not be cut off by it
        let tx0 = w, ty0 = h, tx1 = -1, ty1 = -1;
        for (let y = Math.max(0, y0 - 2); y <= Math.min(h - 1, y1 + 2); y++) for (let x = Math.max(0, x0 - 2); x <= Math.min(w - 1, x1 + 2); x++) {
          const i = px(x, y);
          if ((data[i] - rgb[0]) ** 2 + (data[i + 1] - rgb[1]) ** 2 + (data[i + 2] - rgb[2]) ** 2 > 1600) continue;
          if (x < tx0) tx0 = x; if (x > tx1) tx1 = x; if (y < ty0) ty0 = y; if (y > ty1) ty1 = y;
        }
        const box = tx1 >= 0 ? { x0: tx0, y0: ty0, x1: tx1, y1: ty1 } : { x0, y0, x1, y1 };
        resistors.push({ ...box, rough: { x0, y0, x1, y1 }, horizontal: box.x1 - box.x0 >= box.y1 - box.y0, rgb, color: classifyColor(...rgb) });
      }
      if (!resistors.length) return { ok: false, error: 'No resistors found — paste the Circuit screenshot' };

      // conductors: ink outside the resistor boxes (wires + terminal dots)
      // a resistor's blurred edge isn't wire: drop everything within 2 px of the body, and anything
      // in the rough box that isn't wire-coloured (light grey) — but keep a wire skimming past a corner
      const wireColour = (i) => { const mx = Math.max(data[i], data[i + 1], data[i + 2]), mn = Math.min(data[i], data[i + 1], data[i + 2]); return mx - mn < 45 && mx > 140; };
      const inRes = (x, y) => resistors.some(q => {
        if (x >= q.x0 - 2 && x <= q.x1 + 2 && y >= q.y0 - 2 && y <= q.y1 + 2) return true;
        const R = q.rough;
        return x >= R.x0 - 1 && x <= R.x1 + 1 && y >= R.y0 - 1 && y <= R.y1 + 1 && !wireColour(px(x, y));
      });
      const cond = new Uint8Array(w * h), amber = new Uint8Array(w * h);
      for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
        if (!ink[y * w + x] || inRes(x, y)) continue;
        cond[y * w + x] = 1;
        const i = px(x, y);
        if (isAmber(data[i], data[i + 1], data[i + 2])) amber[y * w + x] = 1;
      }
      const { lab, comps: wires } = components(cond, w, h);

      // the node at each end of a resistor: first wire found just outside the box, near its middle
      const nodeAt = (q, end) => {
        const midX = (q.x0 + q.x1) >> 1, midY = (q.y0 + q.y1) >> 1;
        const spread = q.horizontal ? (q.y1 - q.y0) >> 1 : (q.x1 - q.x0) >> 1;
        const votes = new Map();
        for (let d = 2; d <= r * 3 + 4; d++) {
          for (let s = -spread; s <= spread; s++) {
            let x, y;
            if (q.horizontal) { x = end ? q.x1 + d : q.x0 - d; y = midY + s; }
            else { x = midX + s; y = end ? q.y1 + d : q.y0 - d; }
            if (x < 0 || y < 0 || x >= w || y >= h) continue;
            const L = lab[y * w + x];
            if (L) votes.set(L, (votes.get(L) || 0) + 1);
          }
          if (votes.size) break;
        }
        let best = null, bn = 0;
        votes.forEach((n, L) => { if (n > bn) { bn = n; best = L; } });
        return best;
      };
      resistors.forEach(q => { q.a = nodeAt(q, 0); q.b = nodeAt(q, 1); });

      const { comps: dots } = components(amber, w, h);
      const minDot = Math.max(6, r * r * 0.6);
      const terminals = dots.filter(d => d.n >= minDot).map(d => {
        const counts = new Map();
        for (let y = d.y0; y <= d.y1; y++) for (let x = d.x0; x <= d.x1; x++) {
          const L = lab[y * w + x];
          if (L) counts.set(L, (counts.get(L) || 0) + 1);
        }
        let node = null, bn = 0;
        counts.forEach((n, L) => { if (n > bn) { bn = n; node = L; } });
        return { x: P.x0 + d.cx, y: P.y0 + d.cy, node };
      }).sort((p, q) => p.x - q.x || p.y - q.y);

      const out = resistors
        .sort((p, q) => p.y0 - q.y0 || p.x0 - q.x0)
        .map(q => ({
          x: P.x0 + q.x0, y: P.y0 + q.y0, w: q.x1 - q.x0 + 1, h: q.y1 - q.y0 + 1,
          horizontal: q.horizontal, rgb: q.rgb, color: q.color, a: q.a, b: q.b
        }));
      const unconnected = out.filter(q => q.a == null || q.b == null).length;
      let error = null;
      if (terminals.length !== 2) error = `Found ${terminals.length} orange terminal${terminals.length === 1 ? '' : 's'} (need 2)`;
      else if (unconnected) error = `${unconnected} resistor${unconnected > 1 ? 's' : ''} not connected to a wire on both ends`;
      return {
        ok: !error, error, panel: P, resistors: out, terminals,
        A: terminals[0] ? terminals[0].node : null, B: terminals[1] ? terminals[1].node : null,
        nodeCount: wires.length
      };
    }
    return { classifyColor, components, readCircuit };
  })();

  // ── bomb_boomed/src/modules/circuit/circuitLegend.js ────────────────────────
  const { classifyDigit, readLegend, legendToManual } = (function () {
    // The colour legend picture (colour → ohms): coloured chips on a dark page, each with the colour's
    // name on the left and its value + "Ω" on the right. The values change from game to game, so they
    // are read from the picture: chip colour → name, digits matched by shape.


    const lum = (r, g, b) => 0.299 * r + 0.587 * g + 0.114 * b;
    const dist2 = (data, i, c) => (data[i] - c[0]) ** 2 + (data[i + 1] - c[1]) ** 2 + (data[i + 2] - c[2]) ** 2;

    /** Most common colour in a box (5-bit buckets) → [r, g, b]. */
    function modeColour(data, W, x0, y0, x1, y1) {
      const hist = new Map();
      for (let y = y0; y <= y1; y++) {
        for (let x = x0; x <= x1; x++) {
          const i = (y * W + x) * 4;
          const k = (data[i] >> 3) << 10 | (data[i + 1] >> 3) << 5 | (data[i + 2] >> 3);
          hist.set(k, (hist.get(k) || 0) + 1);
        }
      }
      let bestK = 0, bestN = -1;
      hist.forEach((n, k) => { if (n > bestN) { bestN = n; bestK = k; } });
      // average the real pixels in that bucket
      let r = 0, g = 0, b = 0, n = 0;
      for (let y = y0; y <= y1; y++) {
        for (let x = x0; x <= x1; x++) {
          const i = (y * W + x) * 4;
          if (((data[i] >> 3) << 10 | (data[i + 1] >> 3) << 5 | (data[i + 2] >> 3)) !== bestK) continue;
          r += data[i]; g += data[i + 1]; b += data[i + 2]; n++;
        }
      }
      return [Math.round(r / n), Math.round(g / n), Math.round(b / n)];
    }

    let refCache = null;
    const builtIn = () => (refCache = refCache || DIGIT_REFS.map(r => ({ ch: r.ch, aspect: r.aspect, v: decodeShape(r.fp) })));

    /** Best character ('0'–'9' or 'Ω') for a glyph. learned: { ch: [{ aspect, fp }] }. */
    function classifyDigit(glyph, learned = {}) {
      const refs = builtIn().concat(Object.entries(learned).flatMap(([ch, list]) => list.map(r => ({ ch, aspect: r.aspect, v: decodeShape(r.fp) }))));
      const best = {};
      for (const r of refs) {
        const s = glyphScore(glyph, r);
        if (!(r.ch in best) || s > best[r.ch]) best[r.ch] = s;
      }
      const ranked = Object.entries(best).sort((a, b) => b[1] - a[1]);
      if (!ranked.length) return { ch: null, score: 0, margin: 0, second: null };
      return { ch: ranked[0][0], score: ranked[0][1], margin: ranked.length > 1 ? ranked[0][1] - ranked[1][1] : 1, second: ranked[1] ? ranked[1][0] : null };
    }

    /** Split a glyph box that is too wide for one digit (two digits touching) at its thinnest columns. */
    function splitWide(c, inkAt) {
      const w = c.x1 - c.x0 + 1, h = c.y1 - c.y0 + 1;
      const parts = Math.round(w / (h * 0.62));
      if (parts < 2) return [c];
      const col = [];
      for (let x = c.x0; x <= c.x1; x++) {
        let n = 0;
        for (let y = c.y0; y <= c.y1; y++) if (inkAt(x, y)) n++;
        col.push(n);
      }
      const cuts = [];
      for (let k = 1; k < parts; k++) {
        const mid = Math.round((w * k) / parts), lo = Math.max(1, mid - Math.round(h * 0.2)), hi = Math.min(w - 2, mid + Math.round(h * 0.2));
        let at = mid;
        for (let x = lo; x <= hi; x++) if (col[x] < col[at]) at = x;
        cuts.push(c.x0 + at);
      }
      const edges = [c.x0, ...cuts, c.x1 + 1];
      return edges.slice(0, -1).map((x0, k) => ({ ...c, x0, x1: edges[k + 1] - 1, split: true }));
    }

    /**
     * Read a legend picture.
     * → { ok, reason?, chips: [{ box, rgb, color, value, glyphs: [{ box, glyph, ch, score, margin }], sure }] }
     *   value: the number read (string) or null; sure: every digit read with a clear margin.
     */
    function readLegend(data, W, H, learned = {}) {
      // the page colour: the most common colour along the picture's edge
      const edge = new Map();
      const addEdge = (x, y) => { const i = (y * W + x) * 4; const k = `${data[i] >> 2},${data[i + 1] >> 2},${data[i + 2] >> 2}`; edge.set(k, (edge.get(k) || 0) + 1); };
      for (let x = 0; x < W; x++) { addEdge(x, 0); addEdge(x, H - 1); }
      for (let y = 0; y < H; y++) { addEdge(0, y); addEdge(W - 1, y); }
      const page = [...edge.entries()].sort((a, b) => b[1] - a[1])[0][0].split(',').map(v => Number(v) * 4 + 2);

      const mask = new Uint8Array(W * H);
      for (let p = 0; p < W * H; p++) if (dist2(data, p * 4, page) > 1600) mask[p] = 1;
      const { comps } = components(mask, W, H, false);
      const boxes = comps.filter(c => {
        const bw = c.x1 - c.x0 + 1, bh = c.y1 - c.y0 + 1;
        return c.n >= W * H * 0.01 && bw / bh >= 1.4 && bw / bh <= 6 && c.n >= bw * bh * 0.6;
      });
      if (boxes.length < 2) return { ok: false, reason: 'no colour chips found', chips: [] };

      // rows top to bottom, then left to right
      const rowH = Math.min(...boxes.map(b => b.y1 - b.y0 + 1)) * 0.5;
      boxes.sort((a, b) => (Math.abs(a.cy - b.cy) < rowH ? a.x0 - b.x0 : a.cy - b.cy));

      const chips = boxes.map(b => {
        const bw = b.x1 - b.x0 + 1, bh = b.y1 - b.y0 + 1;
        const ix0 = b.x0 + Math.round(bw * 0.05), ix1 = b.x1 - Math.round(bw * 0.05);
        const iy0 = b.y0 + Math.round(bh * 0.1), iy1 = b.y1 - Math.round(bh * 0.1);
        const rgb = modeColour(data, W, ix0, iy0, ix1, iy1);
        const fillL = lum(...rgb);
        // text is either light on a dark chip or dark on a light one: take the side with more pixels
        let light = 0, dark = 0, lo = 255, hi = 0;
        for (let y = iy0; y <= iy1; y++) {
          for (let x = ix0; x <= ix1; x++) {
            const i = (y * W + x) * 4, L = lum(data[i], data[i + 1], data[i + 2]);
            if (L > fillL + 50) light++;
            if (L < fillL - 50) dark++;
            if (L < lo) lo = L;
            if (L > hi) hi = L;
          }
        }
        const isLight = light >= dark;
        const cut = isLight ? (fillL + hi) / 2 : (fillL + lo) / 2;
        const ink = (r, g, bl) => (isLight ? lum(r, g, bl) > cut : lum(r, g, bl) < cut);
        const inkAt = (x, y) => { const i = (y * W + x) * 4; return ink(data[i], data[i + 1], data[i + 2]); };

        const iw = ix1 - ix0 + 1, ih = iy1 - iy0 + 1;
        const tmask = new Uint8Array(iw * ih);
        for (let y = 0; y < ih; y++) for (let x = 0; x < iw; x++) tmask[y * iw + x] = inkAt(ix0 + x, iy0 + y) ? 1 : 0;
        const glyphs = components(tmask, iw, ih, true).comps
          .filter(c => c.n >= ih * 0.15)
          .map(c => ({ x0: c.x0 + ix0, x1: c.x1 + ix0, y0: c.y0 + iy0, y1: c.y1 + iy0 }))
          .sort((p, q) => p.x0 - q.x0);
        // join pieces that touch or overlap (the Ω is drawn as two halves that meet in the middle)
        const merged = [];
        for (const g of glyphs) {
          const last = merged[merged.length - 1];
          if (last && g.x0 <= last.x1 + 1) {
            last.x0 = Math.min(last.x0, g.x0); last.x1 = Math.max(last.x1, g.x1); last.y0 = Math.min(last.y0, g.y0); last.y1 = Math.max(last.y1, g.y1);
          } else merged.push({ ...g });
        }

        // the number: the run of tall glyphs at the right end (… "2" "0" "Ω"), with only small gaps between
        const run = [];
        for (let k = merged.length - 1; k >= 0; k--) {
          const g = merged[k];
          if (!run.length) { run.unshift(g); continue; }
          const tall = Math.max(...run.map(q => q.y1 - q.y0 + 1));
          if (g.y1 - g.y0 + 1 < tall * 0.6 || run[0].x0 - g.x1 - 1 > tall * 0.45) break;
          run.unshift(g);
        }
        const readBox = (g) => {
          const glyph = inkGlyph(data, W, g.x0, g.y0, g.x1 + 1, g.y1 + 1, ink);
          return { box: g, glyph, ...(glyph ? classifyDigit(glyph, learned) : { ch: null, score: 0, margin: 0 }) };
        };
        // a glyph that matches nothing and is too wide for one digit may be two digits touching
        const read = run.flatMap(g => {
          const whole = readBox(g);
          if (whole.score >= 0.75) return [whole];
          const parts = splitWide(g, inkAt);
          if (parts.length < 2) return [whole];
          const split = parts.map(readBox);
          return split.reduce((a, q) => a + q.score, 0) / split.length > whole.score ? split : [whole];
        });
        const digits = read.filter(g => g.ch !== 'Ω');
        const value = digits.length && digits.every(g => g.ch && /\d/.test(g.ch)) ? String(Number(digits.map(g => g.ch).join(''))) : null;
        const sure = value !== null && digits.every(g => g.score >= 0.75 && g.margin >= 0.1);
        return { box: { x0: b.x0, y0: b.y0, x1: b.x1, y1: b.y1 }, rgb, color: classifyColor(...rgb), value, glyphs: read, digits, sure, light: isLight };
      });
      return { ok: true, chips };
    }

    /** Legend chips → manual text ("Red = 4 Ω" per line), the format the solver reads. */
    function legendToManual(chips) {
      return chips.filter(c => c.value !== null).map(c => `${c.color[0].toUpperCase()}${c.color.slice(1)} = ${c.value} Ω`).join('\n');
    }
    return { classifyDigit, readLegend, legendToManual };
  })();

  // ── bomb_boomed/src/modules/circuit/circuitSolver.js ────────────────────────
  const { CIRCUIT_DEFAULT_MANUAL, CIRCUIT_COLORS, parseCircuitManual, formatOhms, solveCircuit } = (function () {
    // Circuit — equivalent resistance between the two orange terminals.
    // The manual maps resistor colours to ohms ("Red = 2 Ω" …). The circuit is solved by nodal analysis
    // with exact fractions, so series, parallel, shorted corners and bridges all work the same way.

    // An earlier game's table — the values change every game (read from the legend picture); the tests use it
    const CIRCUIT_DEFAULT_MANUAL = `Red = 2 Ω
    Orange = 6 Ω
    Yellow = 16 Ω
    Green = 20 Ω
    Blue = 4 Ω
    Violet = 8 Ω
    White = 10 Ω
    Gray = 12 Ω`;

    const CIRCUIT_COLORS = ['red', 'orange', 'yellow', 'green', 'blue', 'violet', 'white', 'gray'];
    const ALIAS = { purple: 'violet', grey: 'gray', silver: 'gray' };

    /** "Red = 2 Ω …" → { red: '2', … } (values kept as decimal strings for exact maths) */
    function parseCircuitManual(text) {
      const out = {};
      const re = /\b([a-z]+)\s*[=:–-]\s*(\d+(?:\.\d+)?)/gi;
      let m;
      while ((m = re.exec(String(text || '')))) {
        const c = ALIAS[m[1].toLowerCase()] || m[1].toLowerCase();
        if (CIRCUIT_COLORS.includes(c)) out[c] = m[2];
      }
      return out;
    }

    // ---- exact fractions (BigInt) ----
    const babs = a => (a < 0n ? -a : a);
    const gcd = (a, b) => { a = babs(a); b = babs(b); while (b) [a, b] = [b, a % b]; return a || 1n; };
    const F = (n, d = 1n) => { if (d < 0n) { n = -n; d = -d; } const g = gcd(n, d); return [n / g, d / g]; };
    const add = (a, b) => F(a[0] * b[1] + b[0] * a[1], a[1] * b[1]);
    const sub = (a, b) => F(a[0] * b[1] - b[0] * a[1], a[1] * b[1]);
    const mul = (a, b) => F(a[0] * b[0], a[1] * b[1]);
    const div = (a, b) => F(a[0] * b[1], a[1] * b[0]);
    const fromDecimal = (s) => {
      const [i, f = ''] = String(s).split('.');
      return F(BigInt(i + f), 10n ** BigInt(f.length));
    };

    /** Show a fraction: "32", "34/3 ≈ 11.33" */
    function formatOhms(fr) {
      const [n, d] = fr;
      const dec = Number(n) / Number(d);
      const short = String(Math.round(dec * 100) / 100);
      return { exact: d === 1n ? String(n) : `${n}/${d}`, decimal: short, isInteger: d === 1n, value: dec };
    }

    /**
     * @param resistors [{ a, b, color }]  a/b = node ids
     * @param A, B terminal node ids
     * @param manual { color: '8' }
     * @returns { ok, ohms: {exact, decimal, …}, error?, values: [ohms per resistor] }
     */
    function solveCircuit(resistors, A, B, manual) {
      const values = resistors.map(r => (manual[r.color] != null ? manual[r.color] : null));
      const missing = [...new Set(resistors.filter((r, i) => values[i] == null).map(r => r.color))];
      if (missing.length) return { ok: false, values, error: `No value for ${missing.join(', ')} in the manual` };
      if (A == null || B == null) return { ok: false, values, error: 'Need two orange terminals' };
      if (A === B) return { ok: true, values, ohms: formatOhms([0n, 1n]), note: 'terminals are shorted' };

      // only the part of the circuit connected to A matters
      const adj = new Map();
      const link = (x, y) => { if (!adj.has(x)) adj.set(x, []); adj.get(x).push(y); };
      resistors.forEach(r => { link(r.a, r.b); link(r.b, r.a); });
      const seen = new Set([A]), stack = [A];
      while (stack.length) for (const y of adj.get(stack.pop()) || []) if (!seen.has(y)) { seen.add(y); stack.push(y); }
      if (!seen.has(B)) return { ok: false, values, error: 'The terminals are not connected (open circuit)' };

      // nodal analysis: ground B, push 1 A into A, R_eq = V(A)
      const nodes = [...seen].filter(n => n !== B);
      const idx = new Map(nodes.map((n, i) => [n, i]));
      const N = nodes.length;
      const M = Array.from({ length: N }, () => Array.from({ length: N + 1 }, () => [0n, 1n]));
      resistors.forEach((r, k) => {
        if (!seen.has(r.a) || r.a === r.b) return;
        const g = div([1n, 1n], fromDecimal(values[k]));
        const ia = idx.get(r.a), ib = idx.get(r.b);
        if (ia != null) M[ia][ia] = add(M[ia][ia], g);
        if (ib != null) M[ib][ib] = add(M[ib][ib], g);
        if (ia != null && ib != null) { M[ia][ib] = sub(M[ia][ib], g); M[ib][ia] = sub(M[ib][ia], g); }
      });
      M[idx.get(A)][N] = [1n, 1n];
      for (let c = 0; c < N; c++) {
        let p = c;
        while (p < N && M[p][c][0] === 0n) p++;
        if (p === N) return { ok: false, values, error: 'Could not solve the circuit' };
        [M[c], M[p]] = [M[p], M[c]];
        for (let r = 0; r < N; r++) {
          if (r === c || M[r][c][0] === 0n) continue;
          const f = div(M[r][c], M[c][c]);
          for (let k = c; k <= N; k++) M[r][k] = sub(M[r][k], mul(f, M[c][k]));
        }
      }
      const a = idx.get(A);
      return { ok: true, values, ohms: formatOhms(div(M[a][N], M[a][a])) };
    }
    return { CIRCUIT_DEFAULT_MANUAL, CIRCUIT_COLORS, parseCircuitManual, formatOhms, solveCircuit };
  })();

